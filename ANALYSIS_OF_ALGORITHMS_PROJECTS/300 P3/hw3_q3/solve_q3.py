#!/usr/bin/env python3
"""hw3_q3/solve_q3.py

Goal (Q3 bonus): maximize acceptance rate against a *biased* verifier on
graphs generated by `gen_graph` (graphs are intentionally non-3-colorable).

Key idea: learn the verifier's challenge distribution by probing, then
compute a coloring that *minimizes the probability mass* of monochromatic
edges under that distribution.

Empirically, the verifier is heavily biased towards edges incident to a
high-degree / high-mass "hub" vertex (often vertex 0 in graphs generated by
`gen_graph`). We therefore hard-protect all hub-incident edges (always
possible), then solve a weighted Max-3-Cut instance on the remaining sampled
edges using local search.

This file is self-contained and does:
1) generate graphs
2) probe verifier to estimate edge probabilities
3) compute an adversarial coloring that satisfies hot edges
4) measure acceptance using honest_prover.py
"""

