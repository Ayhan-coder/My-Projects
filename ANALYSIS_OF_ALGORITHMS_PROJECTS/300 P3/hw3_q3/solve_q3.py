def choose_protected_hub_neighbors(
    hub: int,
    edge_counts: Dict[Tuple[int, int], int],
    mass_target: float,
) -> Tuple[Set[int], float]:
    """Choose a subset of hub neighbors covering `mass_target` of hub-incident probe mass.

    Returns (protected_neighbors, covered_mass_fraction).
    """

    hub_items: List[Tuple[int, int]] = []
    total = 0
    for (u, v), w in edge_counts.items():
        if u == hub:
            hub_items.append((v, w))
            total += w
        elif v == hub:
            hub_items.append((u, w))
            total += w

    if total <= 0:
        return set(), 0.0

    hub_items.sort(key=lambda x: x[1], reverse=True)
    protected: Set[int] = set()
    acc = 0
    for nb, w in hub_items:
        protected.add(nb)
        acc += w
        if acc / total >= mass_target:
            break
    return protected, acc / total


