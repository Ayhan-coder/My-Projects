def generate_graph(idx: int, size: int, force_regenerate: bool) -> str:
    filename = os.path.join(BASE_DIR, GRAPHS_DIR, f"G_{idx}.txt")
    meta = _graph_meta_path(filename)
    if os.path.exists(filename) and not force_regenerate:
        if _read_size_param(meta) == size:
            return filename

    cmd = ["wsl", "./gen_graph", "--size", str(size)]
    print(f"Generating graph {idx} (size {size})...", flush=True)
    with open(filename, "w", encoding="utf-8") as f:
        subprocess.run(cmd, cwd=BASE_DIR, stdout=f, check=True)
    _write_size_param(meta, size)
    return filename


def generate_graph_to_path(path: str, size: int) -> None:
    cmd = ["wsl", "./gen_graph", "--size", str(size)]
    # gen_graph is a black box; retry a few times if it exits non-zero.
    last_err: Optional[Exception] = None
    for _ in range(3):
        try:
            with open(path, "w", encoding="utf-8") as f:
                subprocess.run(cmd, cwd=BASE_DIR, stdout=f, check=True)
            return
        except Exception as e:
            last_err = e
            time.sleep(0.05)
    if last_err is not None:
        raise last_err


def estimate_hub_bias(graph_path: str, probe_rounds: int) -> float:
    """Quickly estimate hub mass (fraction of endpoints incident to the most-hit vertex).

    Uses a short probe so we can compare candidate graphs cheaply.
    """

    graph_rel = rel_to_base(graph_path)
    counts = probe_edge_distribution(graph_rel, ProbeConfig(rounds=probe_rounds, runs=1, timeout_s=20))
    if not counts:
        return 0.0
    # Compute hub endpoint mass
    n, _edges = read_graph(graph_path)
    if n <= 0:
        return 0.0
    v_mass = vertex_marginal_mass(n, counts)
    hub = max(range(n), key=lambda v: v_mass[v])
    total = sum(counts.values())
    return v_mass[hub] / max(1, 2 * total)


def compute_adversarial_coloring(
    n: int,
    edges: Sequence[Tuple[int, int]],
    adj: List[List[int]],
    edge_counts: Dict[Tuple[int, int], int],
    solve_cfg: SolveConfig,
    rng: random.Random,
) -> Tuple[List[int], int, float]:
    """Return (colors, hub_vertex, protected_hub_mass).

    Chooses between multiple protection strategies and keeps the one with best predicted acceptance.
    """

    weighted_adj = build_weighted_adj(n, edge_counts)
    v_mass = vertex_marginal_mass(n, edge_counts)
    hub = max(range(n), key=lambda v: v_mass[v])

    unit_adj = build_unit_adj(n, edges)

    # Strategies:
    # - hub-protect at varying strengths
    # - unconstrained (no hub fixed), sometimes better for weakly-biased small graphs
    protect_targets = [0.97, 0.985, 0.995, 1.0]
    if FAST_MODE:
        protect_targets = [0.98, 0.99, 1.0]

    candidates: List[Tuple[Optional[float], float]] = [(None, 0.0)]  # (protect_target, placeholder)
    candidates.extend([(t, 0.0) for t in protect_targets])

    best_colors: Optional[List[int]] = None
    best_forbidden: Optional[List[Set[int]]] = None
    best_protected_hub_mass = 0.0
    best_pred_accept = -1.0
    best_bad_edges = 10**18

    for protect_target, _ in candidates:
        protected_hub_mass = 0.0
        forbidden: List[Set[int]] = [set() for _ in range(n)]

        if protect_target is not None:
            # Fix hub to color 0
            forbidden[hub].update({1, 2})
            protected_neighbors, protected_hub_mass = choose_protected_hub_neighbors(
                hub=hub,
                edge_counts=edge_counts,
                mass_target=protect_target,
            )
            for nb in protected_neighbors:
                forbidden[nb].add(0)

            def random_feasible_coloring() -> List[int]:
                colors = [rng.randrange(3) for _ in range(n)]
                colors[hub] = 0
                for nb in protected_neighbors:
                    colors[nb] = 1 if rng.random() < 0.5 else 2
                for v in range(n):
                    if colors[v] in forbidden[v]:
                        choices = [c for c in (0, 1, 2) if c not in forbidden[v]]
                        colors[v] = choices[0] if choices else 0
                return colors

        else:
            # Unconstrained start
            def random_feasible_coloring() -> List[int]:
                return [rng.randrange(3) for _ in range(n)]

        local_best: Optional[List[int]] = None
        local_best_bad = 10**18
        for _ in range(max(1, solve_cfg.restarts)):
            colors = random_feasible_coloring()

            # Greedy best response pass (weighted)
            order = list(range(n))
            rng.shuffle(order)
            for v in order:
                best_c = colors[v]
                best_local = 10**18
                for c in (0, 1, 2):
                    if c in forbidden[v]:
                        continue
                    local = 0
                    for nb, w in weighted_adj[v]:
                        if c == colors[nb]:
                            local += w
                    if local < best_local:
                        best_local = local
                        best_c = c
                colors[v] = best_c

            local_search_minimize_bad(
                colors=colors,
                weighted_adj=weighted_adj,
                forbidden=forbidden,
                steps=solve_cfg.steps_per_restart,
                random_walk_prob=solve_cfg.random_walk_prob,
                rng=rng,
            )

            bad = total_weighted_bad(colors, weighted_adj)
            if bad < local_best_bad:
                local_best_bad = bad
                local_best = colors

        colors = local_best if local_best is not None else random_feasible_coloring()

        # Reduce overall invalid edges a bit without destroying weighted objective.
        local_search_reduce_total_conflicts(
            colors=colors,
            edges=edges,
            unit_adj=unit_adj,
            weighted_adj=weighted_adj,
            forbidden=forbidden,
            steps=max(20_000 if FAST_MODE else 40_000, solve_cfg.steps_per_restart // 2),
            rng=rng,
            alpha_weighted=14,
            beta_unweighted=2,
            random_walk_prob=0.03,
        )

        bad_w, total_w = weighted_conflict_mass(colors, edge_counts)
        bad_mass = (bad_w / total_w) if total_w else 1.0
        pred_accept = (1.0 - bad_mass) ** ROUNDS_PER_PROTOCOL if bad_mass < 1.0 else 0.0
        bad_edges = count_conflicting_edges(colors, edges)

        if (pred_accept > best_pred_accept) or (abs(pred_accept - best_pred_accept) < 1e-12 and bad_edges < best_bad_edges):
            best_pred_accept = pred_accept
            best_bad_edges = bad_edges
            best_protected_hub_mass = protected_hub_mass
            best_colors = list(colors)
            best_forbidden = forbidden

    if best_colors is None:
        best_colors = [rng.randrange(3) for _ in range(n)]
        best_protected_hub_mass = 0.0

    return best_colors, hub, best_protected_hub_mass


def generate_best_graph(idx: int, size: int, force_regenerate: bool) -> str:
    """Generate multiple graphs for the same size and keep the most exploitable one."""

    final_path = os.path.join(BASE_DIR, GRAPHS_DIR, f"G_{idx}.txt")
    meta = _graph_meta_path(final_path)
    if os.path.exists(final_path) and not force_regenerate:
        if _read_size_param(meta) == size:
            return final_path

    best_path = ""
    best_score = -1.0
    best_tiebreak_bad_edges = 10**18
    probe_rounds = 250 if size <= 40 else 450

    # Cheap solve config for selecting candidates
    sel_cfg = SolveConfig(
        restarts=2 if FAST_MODE else 4,
        steps_per_restart=8_000 if FAST_MODE else 18_000,
        random_walk_prob=0.06,
        feedback_iters=0,
        feedback_rounds=200,
        seed=7777 + size * 17,
    )

    pid = os.getpid()
    cand_paths: List[str] = []

    for k in range(1, CANDIDATE_GRAPHS_PER_SIZE + 1):
        cand_path = os.path.join(BASE_DIR, GRAPHS_DIR, f"G_{idx}_cand{k}_{pid}.txt")
        cand_paths.append(cand_path)
        generate_graph_to_path(cand_path, size)
        if not os.path.exists(cand_path):
            continue

        # Score by predicted acceptance under a cheap probe + cheap solve.
        graph_rel = rel_to_base(cand_path)
        edge_counts = probe_edge_distribution(graph_rel, ProbeConfig(rounds=probe_rounds, runs=1, timeout_s=20))
        n, edges = read_graph(cand_path)
        if n <= 0 or not edge_counts:
            continue
        adj: List[List[int]] = [[] for _ in range(n)]
        for u, v in edges:
            adj[u].append(v)
            adj[v].append(u)
        rng = random.Random(sel_cfg.seed + n)
        colors, _hub, _prot = compute_adversarial_coloring(
            n=n,
            edges=edges,
            adj=adj,
            edge_counts=edge_counts,
            solve_cfg=sel_cfg,
            rng=rng,
        )
        bad_w, total_w = weighted_conflict_mass(colors, edge_counts)
        bad_mass = (bad_w / total_w) if total_w else 1.0
        score = (1.0 - bad_mass) ** ROUNDS_PER_PROTOCOL if bad_mass < 1.0 else 0.0
        bad_edges = count_conflicting_edges(colors, edges)
        if (score > best_score) or (abs(score - best_score) < 1e-12 and bad_edges < best_tiebreak_bad_edges):
            best_score = score
            best_tiebreak_bad_edges = bad_edges
            best_path = cand_path

    # Move best into place, delete the others.
    if best_path:
        try:
            os.replace(best_path, final_path)
        except OSError:
            # Fallback: copy then delete
            with open(best_path, "r", encoding="utf-8") as src, open(final_path, "w", encoding="utf-8") as dst:
                dst.write(src.read())
            os.remove(best_path)
        _write_size_param(meta, size)

    for cand_path in cand_paths:
        if os.path.exists(cand_path):
            try:
                os.remove(cand_path)
            except OSError:
                pass

    return final_path


def read_graph(path: str) -> Tuple[int, List[Tuple[int, int]]]:
    with open(path, "r", encoding="utf-8") as f:
        toks = f.read().split()
    if len(toks) < 2:
        return 0, []

    n = int(toks[0])
    m = int(toks[1])
    edge_data = list(map(int, toks[2:]))
    if len(edge_data) != 2 * m:
        # tolerate minor format issues; parse pairs available
        m = len(edge_data) // 2

    edges: List[Tuple[int, int]] = []
    for i in range(0, 2 * m, 2):
        u = edge_data[i]
        v = edge_data[i + 1]
        if u == v:
            continue
        if u > v:
            u, v = v, u
        edges.append((u, v))
    return n, edges


