def solve_one_graph(graph_path: str, coloring_path: str, probe: ProbeConfig, solve_cfg: SolveConfig) -> Dict[str, float]:
    n, edges = read_graph(graph_path)
    if n == 0:
        write_coloring(coloring_path, [])
        return {"n": 0, "m": 0, "hot_mass": 0.0, "bad_mass": 1.0, "pred_accept": 0.0}

    rng = random.Random(solve_cfg.seed + n)

    # Full adjacency (for DSATUR on hot edges only we still need adjacency list)
    adj: List[List[int]] = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)

    graph_rel = rel_to_base(graph_path)
    edge_counts = probe_edge_distribution(graph_rel, probe)
    if not edge_counts:
        # Fallback: random coloring (should not happen)
        colors = [rng.randrange(3) for _ in range(n)]
        write_coloring(coloring_path, colors)
        return {"n": float(n), "m": float(len(edges)), "hot_mass": 0.0, "bad_mass": 1.0, "pred_accept": 0.0}

    # Identify the "hub" vertex under the *observed* distribution.
    v_mass = vertex_marginal_mass(n, edge_counts)
    hub = max(range(n), key=lambda v: v_mass[v])

    total_probe = sum(edge_counts.values())
    hub_mass_total = v_mass[hub] / max(1, 2 * total_probe)

    colors, hub_from_solver, protected_hub_mass = compute_adversarial_coloring(
        n=n,
        edges=edges,
        adj=adj,
        edge_counts=edge_counts,
        solve_cfg=solve_cfg,
        rng=rng,
    )
    hub = hub_from_solver
    forbidden: List[Set[int]] = [set() for _ in range(n)]

    # Optional feedback fine-tuning: only worth doing when we're already near the target.
    base_bad_w, base_total_w = weighted_conflict_mass(colors, edge_counts)
    base_bad_mass = (base_bad_w / base_total_w) if base_total_w else 1.0
    if solve_cfg.feedback_iters > 0 and base_bad_mass <= 0.03:
        for _ in range(solve_cfg.feedback_iters):
            rej = run_verifier_once_collect_reject_edge(
                graph_rel=graph_rel,
                rounds=solve_cfg.feedback_rounds,
                colors=colors,
            )
            if rej is None:
                break
            u, v = rej
            repair_reject_edge(
                colors=colors,
                u=u,
                v=v,
                weighted_adj=weighted_adj,
                forbidden=forbidden,
            )
            local_search_minimize_bad(
                colors=colors,
                weighted_adj=weighted_adj,
                forbidden=forbidden,
                steps=max(4_000, solve_cfg.steps_per_restart // 10),
                random_walk_prob=solve_cfg.random_walk_prob,
                rng=rng,
            )

    # Output
    write_coloring(coloring_path, colors)

    # Metrics
    bad_w, total_w = weighted_conflict_mass(colors, edge_counts)
    bad_mass = (bad_w / total_w) if total_w else 1.0
    pred_accept = (1.0 - bad_mass) ** ROUNDS_PER_PROTOCOL if bad_mass < 1.0 else 0.0

    # Also report how invalid the coloring is on the full edge set (assignment writeup requirement).
    bad_edges = count_conflicting_edges(colors, edges)
    bad_edge_frac = (bad_edges / len(edges)) if edges else 0.0
    return {
        "n": float(n),
        "m": float(len(edges)),
        "hub": float(hub),
        "hub_mass": float(hub_mass_total),
        "protected_hub_mass": float(protected_hub_mass),
        "bad_edges": float(bad_edges),
        "bad_edge_frac": float(bad_edge_frac),
        "bad_mass": float(bad_mass),
        "pred_accept": float(pred_accept),
        "observed_edges": float(len(edge_counts)),
        "hub_deg": float(len(adj[hub])),
    }


def run_experiment(graph_path: str, coloring_path: str) -> Tuple[float, int]:
    """Return (accept_rate, completed_trials)."""

    graph_rel = rel_to_base(graph_path)
    n, _edges = read_graph(graph_path)
    base_colors = read_coloring(coloring_path, n)

    rng = random.Random(99991 + n)
    default_trials = 8 if FAST_MODE else TRIALS_PER_GRAPH
    target_trials = _env_int("Q3_TRIALS", default_trials)
    timeout_s = _env_int("Q3_TRIAL_TIMEOUT_S", 15 if FAST_MODE else 25)
    accepts = 0
    completed = 0
    attempts = 0
    max_attempts = target_trials * 5
    while completed < target_trials and attempts < max_attempts:
        attempts += 1
        out = run_protocol_trial(
            graph_rel=graph_rel,
            rounds=ROUNDS_PER_PROTOCOL,
            base_colors=base_colors,
            rng=rng,
            timeout_s=timeout_s,
        )
        if out is None:
            continue
        completed += 1
        if out:
            accepts += 1

    rate = (accepts / completed) if completed else 0.0
    return rate, completed


