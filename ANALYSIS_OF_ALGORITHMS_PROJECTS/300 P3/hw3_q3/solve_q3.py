# ---------------------------- Probing ----------------------------


def probe_edge_distribution(graph_rel: str, probe: ProbeConfig) -> Dict[Tuple[int, int], int]:
    """Collect many challenges in one (or a few) verifier runs.

    Critical optimization: instead of spawning the verifier per-sample,
    run with `--rounds K` and respond with a fixed non-equal pair (0,1)
    to force the verifier to continue and reveal all K challenged edges.
    """

    counts: DefaultDict[Tuple[int, int], int] = collections.defaultdict(int)

    cmd = ["wsl", "./zk_verifier", "--graph", graph_rel, "--rounds", str(probe.rounds)]
    # If the verifier's sampling adapts to answers, probing with constant answers can skew the
    # distribution. Use random *distinct* pairs to better mimic normal protocol executions.
    rng = random.Random(0)
    distinct_pairs = [(0, 1), (0, 2), (1, 2)]
    for _ in range(probe.runs):
        p = subprocess.Popen(
            cmd,
            cwd=BASE_DIR,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1,
        )
        assert p.stdin and p.stdout

        # Avoid interactive deadlocks: pre-send enough ANSWER lines up-front.
        # The verifier will consume them as it emits CHALLENGE lines.
        answers: List[str] = []
        for _k in range(probe.rounds + 5):
            a, b = distinct_pairs[rng.randrange(len(distinct_pairs))]
            answers.append(f"ANSWER {a} {b}\n")
        p.stdin.write("".join(answers))
        p.stdin.flush()

        start = time.time()
        for raw in p.stdout:
            if time.time() - start > probe.timeout_s:
                break
            line = raw.strip()
            if line.startswith("CHALLENGE"):
                parts = line.split()
                if len(parts) >= 3:
                    u = int(parts[1])
                    v = int(parts[2])
                    if u > v:
                        u, v = v, u
                    counts[(u, v)] += 1
                continue
            if line.startswith("ACCEPT") or line.startswith("REJECT"):
                break

        p.terminate()

    return dict(counts)


def select_hot_edges(
    edge_counts: Dict[Tuple[int, int], int],
    mass_target: float,
    max_edges: int,
) -> Tuple[List[Tuple[int, int]], float]:
    """Pick the smallest prefix of edges covering `mass_target` of observed probes."""

    if not edge_counts:
        return [], 0.0

    total = sum(edge_counts.values())
    items = sorted(edge_counts.items(), key=lambda kv: kv[1], reverse=True)
    hot: List[Tuple[int, int]] = []
    acc = 0
    for (u, v), c in items:
        if len(hot) >= max_edges:
            break
        hot.append((u, v))
        acc += c
        if acc / total >= mass_target:
            break
    return hot, (acc / total if total else 0.0)


# ---------------------------- Weighted local search ----------------------------


def build_weighted_adj(n: int, edge_counts: Dict[Tuple[int, int], int]) -> List[List[Tuple[int, int]]]:
    wadj: List[List[Tuple[int, int]]] = [[] for _ in range(n)]
    for (u, v), w in edge_counts.items():
        wadj[u].append((v, w))
        wadj[v].append((u, w))
    return wadj


def weighted_conflict_mass(colors: Sequence[int], edge_counts: Dict[Tuple[int, int], int]) -> Tuple[int, int]:
    bad = 0
    total = 0
    for (u, v), w in edge_counts.items():
        total += w
        if colors[u] == colors[v]:
            bad += w
    return bad, total


def count_conflicting_edges(colors: Sequence[int], edges: Sequence[Tuple[int, int]]) -> int:
    bad = 0
    for u, v in edges:
        if colors[u] == colors[v]:
            bad += 1
    return bad


def vertex_marginal_mass(n: int, edge_counts: Dict[Tuple[int, int], int]) -> List[int]:
    mass = [0] * n
    for (u, v), w in edge_counts.items():
        mass[u] += w
        mass[v] += w
    return mass


def total_weighted_bad(colors: Sequence[int], weighted_adj: List[List[Tuple[int, int]]]) -> int:
    bad = 0
    for u in range(len(colors)):
        cu = colors[u]
        for v, w in weighted_adj[u]:
            if u < v and cu == colors[v]:
                bad += w
    return bad


def build_weighted_edge_list(edge_counts: Dict[Tuple[int, int], int]) -> Tuple[List[Tuple[int, int, int]], List[int], int]:
    """Return (edges, prefix_sums, total_weight) for weighted sampling."""

    edges: List[Tuple[int, int, int]] = [(u, v, w) for (u, v), w in edge_counts.items()]
    edges.sort(key=lambda e: e[2], reverse=True)
    prefix: List[int] = []
    total = 0
    for _, _, w in edges:
        total += w
        prefix.append(total)
    return edges, prefix, total


def sample_weighted_edge(
    edges: List[Tuple[int, int, int]],
    prefix: List[int],
    total_w: int,
    rng: random.Random,
) -> Tuple[int, int, int]:
    if not edges or total_w <= 0:
        return (0, 0, 0)
    r = rng.randrange(total_w)
    # binary search prefix
    lo, hi = 0, len(prefix) - 1
    while lo < hi:
        mid = (lo + hi) // 2
        if r < prefix[mid]:
            hi = mid
        else:
            lo = mid + 1
    return edges[lo]


def run_verifier_once_collect_reject_edge(
    graph_rel: str,
    rounds: int,
    colors: Sequence[int],
    timeout_s: int = 15,
) -> Optional[Tuple[int, int]]:
    """Run the verifier once using a fixed coloring.

    Returns the rejecting monochromatic edge if the verifier rejects, else None.
    """

    cmd = ["wsl", "./zk_verifier", "--graph", graph_rel, "--rounds", str(rounds)]
    p = subprocess.Popen(
        cmd,
        cwd=BASE_DIR,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
        encoding="utf-8",
        errors="replace",
        bufsize=1,
    )
    assert p.stdin and p.stdout

    start = time.time()
    reject_edge: Optional[Tuple[int, int]] = None
    try:
        while True:
            if time.time() - start > timeout_s:
                break

            line = p.stdout.readline()
            if not line:
                break
            line = line.strip()

            if line.startswith("CHALLENGE"):
                _, us, vs = line.split()
                u = int(us)
                v = int(vs)
                p.stdin.write(f"ANSWER {colors[u]} {colors[v]}\n")
                p.stdin.flush()
                continue

            if line.startswith("REJECT"):
                parts = line.split()
                # Expected format: REJECT monochromatic-edge u v
                ints = [int(x) for x in parts if x.isdigit()]
                if len(ints) >= 2:
                    u, v = ints[-2], ints[-1]
                    if u > v:
                        u, v = v, u
                    reject_edge = (u, v)
                break

            if line.startswith("ACCEPT"):
                break
    finally:
        p.terminate()

    return reject_edge


def read_coloring(path: str, n: int) -> List[int]:
    colors: List[int] = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            colors.append(int(line))
    if len(colors) != n:
        raise ValueError(f"Coloring file has {len(colors)} entries, but graph has {n} vertices")
    for c in colors:
        if c not in (0, 1, 2):
            raise ValueError("Coloring must use only colors {0,1,2}")
    return colors


def run_protocol_trial(
    graph_rel: str,
    rounds: int,
    base_colors: Sequence[int],
    rng: random.Random,
    timeout_s: int = 20,
) -> Optional[bool]:
    """Run one protocol execution and return True/False.

    Returns None on timeout / I/O failure so caller can retry without biasing the estimate.
    """

    perm = [0, 1, 2]
    rng.shuffle(perm)

    cmd = ["wsl", "./zk_verifier", "--graph", graph_rel, "--rounds", str(rounds)]
    p = subprocess.Popen(
        cmd,
        cwd=BASE_DIR,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
        encoding="utf-8",
        errors="replace",
        bufsize=1,
    )
    assert p.stdin and p.stdout

    q: queue.Queue[Optional[str]] = queue.Queue()

    def reader() -> None:
        try:
            for line in p.stdout:  # type: ignore[assignment]
                q.put(line)
        finally:
            q.put(None)

    t = threading.Thread(target=reader, daemon=True)
    t.start()

    deadline = time.time() + timeout_s
    try:
        while True:
            remaining = deadline - time.time()
            if remaining <= 0:
                return None
            try:
                line = q.get(timeout=remaining)
            except queue.Empty:
                return None
            if line is None:
                return None
            line = line.strip()

            if line.startswith("CHALLENGE"):
                parts = line.split()
                if len(parts) < 3:
                    return None
                u = int(parts[1])
                v = int(parts[2])
                cu = perm[base_colors[u]]
                cv = perm[base_colors[v]]
                p.stdin.write(f"ANSWER {cu} {cv}\n")
                p.stdin.flush()
                continue

            if line.startswith("ACCEPT"):
                return True
            if line.startswith("REJECT"):
                return False
    finally:
        try:
            p.terminate()
        except Exception:
            pass
        try:
            p.kill()
        except Exception:
            pass


def repair_reject_edge(
    colors: List[int],
    u: int,
    v: int,
    weighted_adj: List[List[Tuple[int, int]]],
    forbidden: List[Set[int]],
) -> None:
    """Force (u,v) to be bichromatic by recoloring one endpoint with minimal delta."""

    if colors[u] != colors[v]:
        return

    def best_fix_for_vertex(x: int, other_color: int) -> Tuple[int, int]:
        old_c = colors[x]
        best_c = old_c
        best_delta = 10**18
        for new_c in (0, 1, 2):
            if new_c == old_c:
                continue
            if new_c == other_color:
                continue
            if new_c in forbidden[x]:
                continue
            delta = 0
            for nb, w in weighted_adj[x]:
                old_bad = w if old_c == colors[nb] else 0
                new_bad = w if new_c == colors[nb] else 0
                delta += new_bad - old_bad
            if delta < best_delta:
                best_delta = delta
                best_c = new_c
        return best_c, best_delta

    cu, du = best_fix_for_vertex(u, colors[v])
    cv, dv = best_fix_for_vertex(v, colors[u])
    if du <= dv:
        if cu != colors[u]:
            colors[u] = cu
    else:
        if cv != colors[v]:
            colors[v] = cv


def local_search_minimize_bad(
    colors: List[int],
    weighted_adj: List[List[Tuple[int, int]]],
    forbidden: List[Set[int]],
    steps: int,
    random_walk_prob: float,
    rng: random.Random,
) -> None:
    """Local search to minimize weighted monochromatic mass on probed edges.

    Uses a best-improving move most of the time, with occasional random walk
    steps to escape shallow local minima.
    """

    n = len(colors)
    nodes = list(range(n))

    # Prefer selecting endpoints of high-weight *currently conflicting* edges.
    # This empirically converges faster than uniform random vertices.
    # Note: edge_counts includes only probed edges, which is exactly what we optimize.
    edge_counts: Dict[Tuple[int, int], int] = {}
    for u in range(n):
        for v, w in weighted_adj[u]:
            if u < v:
                edge_counts[(u, v)] = edge_counts.get((u, v), 0) + w
    edges, prefix, total_w = build_weighted_edge_list(edge_counts)

    def best_recolor(v: int) -> Tuple[int, int]:
        old_c = colors[v]
        best_c = old_c
        best_delta = 0
        for new_c in (0, 1, 2):
            if new_c == old_c or new_c in forbidden[v]:
                continue
            delta = 0
            for nb, w in weighted_adj[v]:
                old_bad = w if old_c == colors[nb] else 0
                new_bad = w if new_c == colors[nb] else 0
                delta += new_bad - old_bad
            if delta < best_delta:
                best_delta = delta
                best_c = new_c
        return best_c, best_delta

    for _ in range(steps):
        if rng.random() < random_walk_prob:
            v = rng.choice(nodes)
            old_c = colors[v]
            cand = [c for c in (0, 1, 2) if c != old_c and c not in forbidden[v]]
            if cand:
                colors[v] = rng.choice(cand)
            continue

        u, v, _w = sample_weighted_edge(edges, prefix, total_w, rng)
        if u == v:
            continue
        if colors[u] != colors[v]:
            continue

        # Try to fix the conflict by recoloring one endpoint.
        cu, du = best_recolor(u)
        cv, dv = best_recolor(v)
        if du == 0 and dv == 0:
            continue
        if du <= dv:
            colors[u] = cu
        else:
            colors[v] = cv


def build_unit_adj(n: int, edges: Sequence[Tuple[int, int]]) -> List[List[int]]:
    adj: List[List[int]] = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    return adj


def local_search_reduce_total_conflicts(
    colors: List[int],
    edges: Sequence[Tuple[int, int]],
    unit_adj: List[List[int]],
    weighted_adj: List[List[Tuple[int, int]]],
    forbidden: List[Set[int]],
    steps: int,
    rng: random.Random,
    alpha_weighted: int = 10,
    beta_unweighted: int = 1,
    random_walk_prob: float = 0.03,
) -> None:
    """Try to reduce total number of monochromatic edges while keeping weighted bad mass low.

    Objective uses a linear combination:
      score = alpha_weighted * (delta weighted-bad) + beta_unweighted * (delta unweighted-bad)
    """

    n = len(colors)
    nodes = list(range(n))

    def delta_unweighted(v: int, old_c: int, new_c: int) -> int:
        d = 0
        for nb in unit_adj[v]:
            d -= 1 if old_c == colors[nb] else 0
            d += 1 if new_c == colors[nb] else 0
        return d

    def delta_weighted(v: int, old_c: int, new_c: int) -> int:
        d = 0
        for nb, w in weighted_adj[v]:
            d -= w if old_c == colors[nb] else 0
            d += w if new_c == colors[nb] else 0
        return d

    for _ in range(steps):
        v = rng.choice(nodes)
        old_c = colors[v]

        if rng.random() < random_walk_prob:
            cand = [c for c in (0, 1, 2) if c != old_c and c not in forbidden[v]]
            if cand:
                colors[v] = rng.choice(cand)
            continue

        best_c = old_c
        best_score = 0
        for new_c in (0, 1, 2):
            if new_c == old_c or new_c in forbidden[v]:
                continue
            dw = delta_weighted(v, old_c, new_c)
            du = delta_unweighted(v, old_c, new_c)
            score = alpha_weighted * dw + beta_unweighted * du
            if score < best_score:
                best_score = score
                best_c = new_c
        if best_c != old_c:
            colors[v] = best_c


